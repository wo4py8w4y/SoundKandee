enum class AudioSourceType(val label: String, val subtitle: String) {
    OUTPUT_MIX("Output Mix", "Global device audio output (Session 0)"),
    APP_PLAYBACK("App Audio", "Direct playback capture from other apps (Android 10+)"),
    MICROPHONE("Microphone", "Live ambient microphone input"),
